param([switch]$NativeBuild, [switch]$SkipFixture)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path "$PSScriptRoot/../..").Path
$out = Join-Path $repo 'out/direct-renderer/m1b'
New-Item -ItemType Directory -Force $out | Out-Null
$vs = & "${env:ProgramFiles(x86)}/Microsoft Visual Studio/Installer/vswhere.exe" -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
$msvc = (Get-ChildItem "$vs/VC/Tools/MSVC" -Directory | Sort-Object Name -Descending | Select-Object -First 1).FullName
$sdki = 'C:/SFBundle/winsdk/microsoft.windows.sdk.cpp/c/Include/10.0.26100.0'
$sdkl = 'C:/SFBundle/winsdk/microsoft.windows.sdk.cpp.x64/c'
$fxc = 'C:/SFBundle/winsdk/microsoft.windows.sdk.cpp/c/bin/10.0.26100.0/x64/fxc.exe'
$oldInclude=$env:INCLUDE; $oldLib=$env:LIB; $oldPath=$env:PATH
try {
    $env:INCLUDE="$msvc/include;$sdki/ucrt;$sdki/um;$sdki/shared;$sdki/winrt"
    $env:LIB="$msvc/lib/x64;$sdkl/ucrt/x64;$sdkl/um/x64"
    $env:PATH="$msvc/bin/Hostx64/x64;$oldPath"
    $header = "// Generated by tools/direct-renderer/check-m1b.ps1; do not edit.`n"
    foreach ($entry in @('vs VS vs_5_0','ps PS ps_5_0','pspoint PSPoint ps_5_0','psadd PSAdd ps_5_0','psaddpoint PSAddPoint ps_5_0','psmask PSMask ps_5_0','psmaskpoint PSMaskPoint ps_5_0','psgrab PSGrab ps_5_0','psgrabpoint PSGrabPoint ps_5_0')) {
        $a=$entry.Split(' ')
        & $fxc /nologo /T $a[2] /E $a[1] /O3 /Fh "$out/$($a[0]).h" /Vn "dr2_$($a[0])" "$repo/native/sfnative/dr2.hlsl" > "$out/shader-$($a[0]).log" 2>&1
        if ($LASTEXITCODE) { throw "Shader failed: $entry (see $out)" }
        $header += [IO.File]::ReadAllText("$out/$($a[0]).h")
    }
    $header=[regex]::Replace($header,'[ \t]+(?=\r?$)','',[Text.RegularExpressions.RegexOptions]::Multiline)
    [IO.File]::WriteAllText("$repo/native/sfnative/dr2_shader_bytes.h",$header,(New-Object Text.UTF8Encoding($false)))
    'DR2 shaders: 9 compiled'
    Push-Location $out
    try {
        & cl.exe /nologo /std:c++17 /EHsc /O2 /fp:strict /MT /W4 /WX "$PSScriptRoot/check-m1b.cpp" /Fe:check-m1b.exe d3d11.lib d3dcompiler.lib > build-fixture.log 2>&1
        if ($LASTEXITCODE) { throw "Fixture build failed (see $out/build-fixture.log)" }
        if (!$SkipFixture) {
            # WARP software device only; this neither launches nor injects into the game.
            & ./check-m1b.exe > fixture.log 2>&1
            if ($LASTEXITCODE) { throw "Fixture failed (see $out/fixture.log)" }
            Get-Content fixture.log
        }
    } finally { Pop-Location }
    if ($NativeBuild) {
        $before = & dumpbin.exe /nologo /exports "$repo/native/sfnative.dll"
        $before | Set-Content "$out/exports-before.txt"
        $ErrorActionPreference='Continue'
        try { & "$repo/native/build-sfnative.bat" $msvc $sdki $sdkl 'C:/SFBundle/tools/ispc-v1.31.0-windows/bin' > "$out/build-native.log" 2>&1; $nativeExit=$LASTEXITCODE }
        finally { $ErrorActionPreference='Stop' }
        if ($nativeExit) { throw "Native build failed (see $out/build-native.log)" }
        $after = & dumpbin.exe /nologo /exports "$repo/native/sfnative.dll"
        $after | Set-Content "$out/exports-after.txt"
        $pattern='^\s+(\d+)\s+([0-9A-F]+)\s+[0-9A-F]+\s+(\S+)\s*$'
        $b=@($before | ForEach-Object { if ($_ -match $pattern) { "$($Matches[1]) $($Matches[2]) $($Matches[3])" } })
        $a=@($after | ForEach-Object { if ($_ -match $pattern) { "$($Matches[1]) $($Matches[2]) $($Matches[3])" } })
        if (!$b.Count -or (Compare-Object $b $a)) { throw 'Native export/ordinal mismatch' }
        "Native exports preserved: $($a.Count)" | Tee-Object -FilePath "$out/exports-result.txt"
    }
} finally { $env:INCLUDE=$oldInclude; $env:LIB=$oldLib; $env:PATH=$oldPath }
