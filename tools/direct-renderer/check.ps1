param([switch]$NativeBuild,[switch]$CompileOnly)
$ErrorActionPreference='Stop'
$repo=(Resolve-Path "$PSScriptRoot/../..").Path
$out=Join-Path $repo 'out/direct-renderer'
if($CompileOnly -and $NativeBuild){throw 'CompileOnly cannot rebuild the native DLL'}
if(!$CompileOnly -and (Get-Process -Name 'A Dance of Fire and Ice' -ErrorAction SilentlyContinue)){throw 'Do not build or run offline fixtures during a game run'}
New-Item -ItemType Directory -Force $out | Out-Null
$vs=& "${env:ProgramFiles(x86)}/Microsoft Visual Studio/Installer/vswhere.exe" -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
$msvc=(Get-ChildItem "$vs/VC/Tools/MSVC" -Directory | Sort-Object Name -Descending | Select-Object -First 1).FullName
$sdki='C:/SFBundle/winsdk/microsoft.windows.sdk.cpp/c/Include/10.0.26100.0'
$sdkl='C:/SFBundle/winsdk/microsoft.windows.sdk.cpp.x64/c'
$fxc='C:/SFBundle/winsdk/microsoft.windows.sdk.cpp/c/bin/10.0.26100.0/x64/fxc.exe'
$oldInclude=$env:INCLUDE;$oldLib=$env:LIB;$oldPath=$env:PATH
try{
    $env:INCLUDE="$msvc/include;$sdki/ucrt;$sdki/um;$sdki/shared;$sdki/winrt"
    $env:LIB="$msvc/lib/x64;$sdkl/ucrt/x64;$sdkl/um/x64"
    $env:PATH="$msvc/bin/Hostx64/x64;$oldPath"
    foreach($stage in @('vs','ps')){
        & $fxc /nologo /T "${stage}_5_0" /E $stage.ToUpper() /O3 /Fh "$out/$stage.h" /Vn "dr_$stage" "$repo/native/sfnative/direct_renderer.hlsl"
        if($LASTEXITCODE){throw 'shader compilation failed'}
    }
    $bytes="// Generated by tools/direct-renderer/check.ps1; do not edit.`n"+[IO.File]::ReadAllText("$out/vs.h")+[IO.File]::ReadAllText("$out/ps.h")
    $bytes=[regex]::Replace($bytes,'[ \t]+(?=\r?$)','',[Text.RegularExpressions.RegexOptions]::Multiline)
    [IO.File]::WriteAllText("$repo/native/sfnative/direct_shader_bytes.h",$bytes,(New-Object Text.UTF8Encoding($false)))
    Push-Location $out
    try{
        & cl.exe /nologo /std:c++17 /EHsc /O2 /fp:strict /MT /W4 /WX "$PSScriptRoot/check.cpp" /Fe:check.exe d3d11.lib
        if($LASTEXITCODE){throw 'offline fixture build failed'}
        if($CompileOnly){return}
        & ./check.exe
        if($LASTEXITCODE){throw 'offline fixture failed'}
        & dotnet run --project "$PSScriptRoot/ease/EaseCheck.csproj" -- "$out/native-ease.csv"
        if($LASTEXITCODE){throw 'DOTween easing fixture failed'}
    }finally{Pop-Location}
    if($NativeBuild){
        # Windows PowerShell represents native stderr warnings as ErrorRecords.
        # Preserve the compiler exit code as the pass/fail criterion.
        $ErrorActionPreference='Continue'
        try{& "$repo/native/build-sfnative.bat" $msvc $sdki $sdkl 'C:/SFBundle/tools/ispc-v1.31.0-windows/bin' 2>&1 | ForEach-Object { "$_" };$nativeExit=$LASTEXITCODE}
        finally{$ErrorActionPreference='Stop'}
        if($nativeExit){throw 'full native build failed'}
    }
}finally{$env:INCLUDE=$oldInclude;$env:LIB=$oldLib;$env:PATH=$oldPath}
