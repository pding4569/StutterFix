using StutterFix;
using UnityEngine;
using UnityEngine.Rendering;

int checks=0;
void Check(bool ok,string label) {checks++;if(!ok)throw new Exception(label);}
var gpu=new GpuDecoGpu();
var targets=new[]{new GraphicsBuffer(GraphicsBuffer.Target.Raw,36,4),new GraphicsBuffer(GraphicsBuffer.Target.Raw,36,4)};
GpuDecoCopy.Enabled=GpuDecoCopy.MaskedEnabled=true;
Check(!GpuDecoCopy.SingleSubmission,"default off");
var copy=GpuDecoCopy.TryCreate(gpu.shader,gpu.vertices,targets,8);
Check(copy!=null && GpuDecoCopy.ActiveContexts==1,"native context prepared");
Check(copy.Execute(3,5),"original copy works");
var original=Graphics.Last;
Check(original.Ops.Count(x=>x.Op=="dispatch")==1 && original.Ops[^1].Op=="event","original copy/event sequence");
Check(copy.Execute(6,7,gpu,new Vector4(1,2,3,4),260.123456789),"combined frame works");
var combined=Graphics.Last;
var ops=combined.Ops;
Check(Graphics.Executions==2 && Adapter.Submits==2,"one execute and one mask per frame");
Check(Adapter.Low==6 && Adapter.High==7,"mask preserved");
Check(ops.Where(x=>x.Op=="dispatch").Select(x=>x.Key).SequenceEqual(new[]{"1","2"}),"evaluate precedes normalize");
Check(ops[^1].Op=="event","copy callback is last");
foreach(var key in new[]{"_LiveChannels","_SourceE","_Static","_UV","_Values","_Vertices"})
    Check(ops.Any(x=>x.Op=="buffer" && x.Key=="1:"+key),"bind "+key);
Check(!ops.Any(x=>x.Key=="1:_ImageShape"),"optional image buffer absent");
Check(ops.Any(x=>x.Key=="_UseLiveChannels" && (int)x.Value==1),"live clock semantics");
Check(ops.Any(x=>x.Key=="_CopyQuantizeColor" && (int)x.Value==1),"draw quantization preserved");
Check(ops.Any(x=>x.Key=="_Camera" && ((Vector4)x.Value).x==1),"current camera");
float hi=(float)260.123456789;
Check((float)ops.Single(x=>x.Key=="_TimeHi").Value==hi && (float)ops.Single(x=>x.Key=="_TimeLo").Value==(float)(260.123456789-hi),"time split preserved");
gpu.hasImageGeometry=true;
Check(copy.Execute(8,9,gpu,new Vector4(11,12,13,14),270.987654321),"next frame works");
Check(ReferenceEquals(combined,Graphics.Last) && combined.Clears==2,"command object reused and cleared");
Check(combined.Ops.Count(x=>x.Op=="dispatch")==2,"no stale dispatch accumulation");
Check(combined.Ops.Any(x=>x.Key=="1:_ImageShape" && ReferenceEquals(x.Value,gpu.imageShapeBuffer)),"image binding");
Check(((Vector4)combined.Ops.Single(x=>x.Key=="_Camera").Value).x==11,"camera refreshed");
Check(GpuDecoCopy.SingleExecutions==2,"only successful combined frames counted");
GpuDecoCopy.AblateDestinations=true;
Check(copy.Execute(10,11,gpu,default,271),"ablation records frame");
Check(Adapter.Low==0 && Adapter.High==0,"ablation omits destinations only");
GpuDecoCopy.AblateDestinations=false;
copy.Dispose();copy.Dispose();
Check(original.Disposed && combined.Disposed && Adapter.Destroyed==1 && GpuDecoCopy.ActiveContexts==0,"idempotent release of both command buffers/context");
copy=GpuDecoCopy.TryCreate(gpu.shader,gpu.vertices,targets,8);
gpu.UseLiveMode=false;
int submits=Adapter.Submits,executions=Graphics.Executions;
Check(!copy.Execute(1,2,gpu,default,272),"unsupported evaluator rejected");
Check(Adapter.Submits==submits && Graphics.Executions==executions,"record failure consumes no mask and submits no work");
Check(!copy.Execute(),"failed context stays failed");copy.Dispose();gpu.UseLiveMode=true;
copy=GpuDecoCopy.TryCreate(gpu.shader,gpu.vertices,targets,8);Adapter.Reject=true;
Check(!copy.Execute(1,2,gpu,default,273),"native mask rejection fails");
Check(Graphics.Executions==executions,"rejected mask never executes commands");copy.Dispose();
Check(GpuDecoCopy.ReadTotals().Errors==2,"failures visible to acceptance");
Console.WriteLine($"Single submission production recording/lifecycle: {checks} checks passed; managed adapters, no live GPU/pixel/FPS proof");
