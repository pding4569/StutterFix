$ErrorActionPreference = 'Stop'
$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$rows = Get-Content -LiteralPath (Join-Path $root 'docs/handoff/tilerange-evidence/t3-game-writers.txt')
$specs = [System.Collections.Generic.List[string]]::new()
$specialWriters = @{}
foreach ($block in (($rows -join "`n") -split '(?m)(?=^\S)')) {
    if ($block -match 'UnityEngine.Transform::(set_position|set_rotation|set_localScale|set_eulerAngles|set_localPosition|set_localEulerAngles|SetPositionAndRotation)|(?:Stfld|Ldflda) scrFloor::(opacity|startPos|startRot|tweenRot)\b') {
        $specialWriters[($block -split "`n")[0]] = $true
    }
}
foreach ($row in $rows) {
    if ($row -notmatch '^(.+)::(.+) token=0x[0-9A-F]+ signature=([0-9A-F]+)$') { continue }
    $typeName, $methodName, $signature = $Matches[1], $Matches[2], $Matches[3]
    $mode = 0
    $select = $false
    if ($typeName -eq 'scrFloor') {
        $select = $methodName -in @('Awake','Reset','LateUpdate','TweenRotation','TweenOpacity','MoveToBack','MoveBackBy','SetRotation','ResetToLevelStart','<TweenRotation>b__203_1','<TweenRotation>b__203_2','<TweenOpacity>b__204_1')
        if ($methodName -in @('Awake','Reset','TweenRotation','TweenOpacity','MoveToBack','MoveBackBy','SetRotation','ResetToLevelStart')) { $mode = 1 }
    }
    if ($typeName -in @('scnGame','scrLevelMaker')) {
        $select = $methodName -in @('ApplyEventsToFloors','PrepVfx','ResetScene','MakeLevel','ResetFloor','MakeFreeroamGrid')
        if ($methodName -in @('ResetScene','MakeLevel')) { $mode = 2 }
    }
    if ($typeName -eq 'ffxFloorAppearPlus' -or $typeName -eq 'ffxLightBridge' -or $typeName.StartsWith('ffxLightBridge+')) { $select = $true }
    if ($typeName.StartsWith('ffxMoveFloorPlus+')) { $select = $methodName -notlike '*b__5' }
    if ($typeName -eq 'ffxMoveFloorPlus' -and $methodName -eq 'StartEffect') { $select = $true; $mode = 3 }
    if ($typeName -in @('ffxFloorAppearPlus','ffxFloorDisappearPlus') -and $methodName -eq 'StartEffect') { $select = $true; $mode = 4 }
    if ($typeName -eq 'FreeroamArea' -and $methodName -eq '.ctor') { $select = $true; $mode = 5 }
    if ($typeName -in @('DivineIntervention','LaserSpawner','Mawaru','SingSing_Notefield','TaroBGScript','ThirdSun','scnMinesweeper','Cutscene1','PuzzleRoom','scnTaroMenu2') -and $specialWriters.ContainsKey($row)) { $select = $true }
    if ($select) { $specs.Add('            new Spec("' + $typeName + '","' + $methodName + '","' + $signature + '",' + $mode + '),') }
}
if ($specs.Count -lt 20 -or $specs.Count -gt 64) { throw "Unexpected target count $($specs.Count)" }
$content = @('#if DEV || AUTOTEST','// Generated by tools/tilerange-fixture/generate-writer-manifest.ps1 from the offline IL inventory.','namespace StutterFix { internal static partial class FloorRangeWriters {','    private static readonly Spec[] Manifest = new Spec[] {') + $specs.ToArray() + @('    };','} }','#endif')
[System.IO.File]::WriteAllLines((Join-Path $root 'FloorRangeWriterManifest.cs'), $content, [System.Text.UTF8Encoding]::new($false))
Write-Output "Manifest targets=$($specs.Count)"
