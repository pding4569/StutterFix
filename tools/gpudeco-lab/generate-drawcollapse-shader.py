"""Generate explicit SM5 resource branches; no dynamic resource indexing or extra samplers."""
from pathlib import Path
import re

policy = (Path(__file__).resolve().parents[2] / 'DrawCollapsePolicy.cs').read_text(encoding='utf-8-sig')
arrays = int(re.search(r'const int ArrayBindings=(\d+);', policy).group(1))
direct = int(re.search(r'const int DirectBindings=(\d+);', policy).group(1))
assert arrays + direct <= 64, 'Unity shader texture parameter limit exceeded'
# 배열 텍스처는 모든 구간이 같은 것을 쓰므로 전역(_SfDecoTex*)으로 한 번만 묶고 Properties 에 두지 않는다(재질 속성이 적을수록 그리기 호출마다 드는 CPU 가 준다).
properties = ''
# 직접 텍스처는 Properties 에 두지 않는다: 재질이 값을 갖지 않으면 전역 텍스처(Shader.SetGlobalTexture)를 쓴다.
declarations = '\n'.join(f'            Texture2DArray _SfDecoTex{i};' for i in range(arrays))
few = int(re.search(r'const int FewDirectBindings=(\d+);', policy).group(1))
declarations += '\n#if defined(DIRECT_FEW)\n' + '\n'.join(f'            Texture2D _Big{i};' for i in range(few)) + f'\n            float _DirectMap[{direct}];'
declarations += '\n#elif !defined(NO_DIRECT_TEXTURES)\n' + '\n'.join(f'            Texture2D _Big{i};' for i in range(direct)) + '\n#endif'
def leaf(i):
    texture = f'_SfDecoTex{i}' if i < arrays else f'_Big{i-arrays}'
    coord = 'float3(uv,asfloat(v.info.y))' if i < arrays else 'uvIn'
    return (f'if(usePoint) c={texture}.SampleLevel(sampler_point_clamp,{coord},0); '
            f'else c={texture}.SampleLevel(sampler_linear_clamp,{coord},0);')
def tree(lo, hi, indent):
    if lo == hi:
        return f'{indent}{{ {leaf(lo)} }}'
    mid = (lo + hi) // 2
    left = tree(lo, mid, indent + '    ')
    right = tree(mid + 1, hi, indent + '    ')
    nl = chr(10)
    return f'{indent}[branch] if(binding<={mid}) {{' + nl + left + nl + f'{indent}}} else {{' + nl + right + nl + f'{indent}}}'
branches = ['#ifdef NO_DIRECT_TEXTURES', tree(0, arrays - 1, '                '),
            '#elif defined(DIRECT_FEW)',
            f'                // 구간이 쓰는 직접 텍스처만 {few}칸에 다시 매긴다(재질의 _DirectMap). 그림은 같고 바인딩 수·셰이더 크기만 준다.',
            tree(0, arrays + few - 1, '                '),
            '#else', tree(0, arrays + direct - 1, '                '), '#endif']
shader = '''// Generated by generate-drawcollapse-shader.py. Unity D3D11: TEXTURE_COUNT textures (ARRAY_COUNT with NO_DIRECT_TEXTURES), two samplers.
Shader "StutterFix/GpuDecoBatch"
{
    Properties
    {
PROPERTIES
        [HideInInspector] _LodMode ("LOD mode", Float) = 0
        _SrcBlend ("Source blend", Float) = 1
        _DstBlend ("Destination blend", Float) = 10
        _BlendOp ("Blend operation", Float) = 0
    }
    SubShader
    {
        Tags { "Queue"="Transparent" "IgnoreProjector"="True" "RenderType"="Transparent" "DisableBatching"="True" }
        Cull Off
        Lighting Off
        ZWrite Off
        ZTest LEqual
        Blend [_SrcBlend] [_DstBlend]
        BlendOp [_BlendOp]
        Pass
        {
            HLSLPROGRAM
            #pragma target 5.0
            #pragma only_renderers d3d11
            #pragma vertex vert
            #pragma fragment frag
            #pragma multi_compile_local _ NO_DIRECT_TEXTURES DIRECT_FEW
            #pragma multi_compile_local _ SF_SIMPLE
            #include "UnityCG.cginc"
DECLARATIONS
            SamplerState sampler_point_clamp;
            SamplerState sampler_linear_clamp;
            ByteAddressBuffer _CollapseVerts;
            float _LodMode;
            float4x4 _LodDrawVP;
            float _SfDebugFlat;
            float _SfNoDiscard;
            float _SfDebugMode;   // 측정: 1 이면 투명 픽셀 버리기를 끈다
            float4 _LodTarget;
            StructuredBuffer<int> _LodBox;   // 저해상도 합성 범위(구간마다 화면 픽셀 minX,minY,maxX,maxY, 위에서 아래)
            float _LodSpan;
            Texture2D _LodTex;
            struct appdata { float3 vertex:POSITION; };
#ifndef SF_SIMPLE
            struct v2f { float4 vertex:SV_POSITION; float4 color:COLOR; float2 uv:TEXCOORD0; nointerpolation uint2 info:TEXCOORD1; nointerpolation float4 region:TEXCOORD2;
#ifdef SF_BLEND
                float4 grabPos:TEXCOORD3;
#endif
            };
            v2f vert(appdata v)
            {
                // 정점 번호(x)로 전역 버퍼에서 위치·색·UV·텍스처 정보를 읽는다(60바이트: 위치 12, 색 16, uv+info 16, region 16).
                uint a=(uint)(v.vertex.x+0.5)*60u;
                float3 p=asfloat(_CollapseVerts.Load3(a));
                float4 uvi=asfloat(_CollapseVerts.Load4(a+28));
                v2f o;
                // 합치기 모드(렌더러 MPB): 정점 x 는 모서리 번호 0~3, 화면 전체 사각형을 그린다(저해상도 그림을 원래 순서 자리에 섞는다).
                if(_LodMode>0.5 && _LodMode<1.5)
                {
                    uint cid=(uint)(v.vertex.x+0.5);
                    // 이번 프레임 구간 화면 범위만 덮는다(예전: 화면 전체를 구간마다 합성해 DD 119 FPS)
                    uint sb=(uint)(_LodSpan+0.5)*4u;int4 bx=int4(_LodBox[sb],_LodBox[sb+1],_LodBox[sb+2],_LodBox[sb+3]);
                    float2 px=float2((cid==1||cid==2)?bx.z:bx.x,cid>=2?bx.y:bx.w);
                    if(bx.z<bx.x || bx.w<bx.y)px=0;
                    o.vertex=float4(px.x*_LodTarget.z*2-1,1-px.y*_LodTarget.w*2,UNITY_NEAR_CLIP_VALUE,1);
                    o.color=1;o.uv=0;o.info=0;o.region=0;
#ifdef SF_BLEND
                    o.grabPos=0;
#endif
                    return o;
                }
                // 저해상도 RT도 범위 계산과 같은 GPU 투영을 쓴다. SetRenderTarget에 따른 암묵적 Y 반전에 기대지 않는다.
                o.vertex=_LodMode>1.5?mul(_LodDrawVP,mul(unity_ObjectToWorld,float4(p,1))):UnityObjectToClipPos(float4(p,1));
                o.color=asfloat(_CollapseVerts.Load4(a+12));o.uv=uvi.xy;o.region=asfloat(_CollapseVerts.Load4(a+44));
                uint fx=(uint)(uvi.z+0.5);uint binding=fx&127u;
#if defined(DIRECT_FEW) && !defined(NO_DIRECT_TEXTURES)
                if(binding>=ARRAY_COUNT)binding=ARRAY_COUNT+(uint)_DirectMap[binding-ARRAY_COUNT];
#endif
                // info의 두 성분 크기는 그대로. 레이어는 비트 재해석만 하여 원래 float를 정확히 보존한다.
                o.info=uint2((fx&~127u)|binding,asuint(uvi.w));
#ifdef SF_BLEND
                o.grabPos=ComputeGrabScreenPos(o.vertex);
#endif
                return o;
            }
            float4 frag(v2f v):SV_Target
            {
                if(_LodMode>0.5 && _LodMode<1.5)return _LodTex.SampleLevel(sampler_linear_clamp,v.vertex.xy*_LodTarget.zw,0);
                // 측정 전용 전역 값: 1 이면 텍스처 없이 색만(픽셀 셰이더 비용 가르기)
                if(_SfDebugFlat>0.5){float4 f=v.color;f.rgb*=f.a;return f*0.25;}
                if(_SfDebugMode>2.5)discard;   // 측정 전용 3: 아무것도 안 읽고 버림(픽셀 처리 시작 비용)
                // info.x = 바인딩 + 점 샘플링 128 + 반복 256. 반복이면 UV 를 frac 으로 감싼다(게임의 Repeat 랩, 이음매 반 텍셀만 다름).
                uint fx=v.info.x;bool usePoint=(fx&128u)!=0;bool wrapU=(fx&256u)!=0;bool wrapV=(fx&512u)!=0;int binding=(int)(fx&127u);
                float2 uvIn=float2(wrapU?frac(v.uv.x):v.uv.x,wrapV?frac(v.uv.y):v.uv.y);
                // 모든 텍스처가 밉 1단이라 SampleLevel(0) 은 SampleGrad 와 같다(미분·그래디언트 필요 없음).
                // Clamp to the copied rectangle's texel centres so padded BC blocks never bleed.
                float2 uv=clamp(uvIn*v.region.xy,v.region.zw,v.region.xy-v.region.zw);
                float4 c=0;
BRANCHES
                // 텍스처 알파가 정확히 0 인 픽셀은 어느 섞기 모드에서도 화면을 바꾸지 않는다: 섞기(ROP) 전에 버린다.
                // 겹친 큰 투명 여백이 많은 맵(DD 55초: 228개, 약 138화면분)에서 섞기 대역이 구간 그리기 비용의 대부분이었다.
                if(_SfNoDiscard<0.5 && c.a<=0.0)discard;
                // 측정 전용: 1 = 읽은 뒤 전부 버림(섞기 없는 비용), 2 = 화면 2x2 중 1 픽셀만 남김(섞는 양 1/4)
                if(_SfDebugMode>0.5){if(_SfDebugMode<1.5 || (((uint)v.vertex.x|(uint)v.vertex.y)&1u)!=0u)discard;}
#ifdef SF_BLEND
                // 혼합 모드(Blend Modes 에셋의 SpritesDefault/UnifiedGrab 과 같은 식). 화면 복사본은 같은 이름의 GrabPass 를 공유한다.
                // 모드 번호 = info.x / 1024 (그 에셋의 키워드 순서): 1 Darken 2 Multiply 4 LinearBurn 6 Lighten 7 Screen 9 LinearDodge
                // 11 Overlay 12 SoftLight 18 Difference 19 Exclusion 20 Subtract 21 Divide. 출력은 (결과*알파, 알파)로 원래와 같다.
                int bm=(int)(fx>>10);
                if(bm>0)
                {
                    c*=v.color;
                    float3 b=_BLENDMODES_UnifiedGrabTexture.SampleLevel(sampler_linear_clamp,v.grabPos.xy/v.grabPos.w,0).rgb;
                    float3 sc=c.rgb, r=sc;
                    if(bm==1) r=min(b,sc);
                    else if(bm==2) r=b*sc;
                    else if(bm==4) r=b+sc-1.0;
                    else if(bm==6) r=max(b,sc);
                    else if(bm==7) r=1.0-(1.0-b)*(1.0-sc);
                    else if(bm==9) r=b+sc;
                    else if(bm==11) r=(b>0.5)?(1.0-2.0*(1.0-b)*(1.0-sc)):(2.0*b*sc);
                    else if(bm==12) r=(b*(1.0-b))*sc+(1.0-(1.0-b)*(1.0-sc))*b;
                    else if(bm==18) r=abs(b-sc);
                    else if(bm==19) r=b+sc-2.0*b*sc;
                    else if(bm==20) r=b-sc;
                    else if(bm==21) r=saturate(b/sc);
                    return float4(r*c.a,c.a);
                }
#endif
                // 더하기(9): 미리 곱한 섞기에 (s*a, 0) = d + a*s (Particles/Additive, Blend Modes LinearDodge 와 같은 값). 화면 복사 없음.
                if((fx>>10)==9u){c*=v.color;return float4(c.rgb*c.a,0);}
                c*=v.color;c.rgb*=c.a;return c;
            }
#else
            // 측정 전용 SF_SIMPLE: 넘기는 값을 원래 스프라이트 수준(위치·색·UV)으로 줄인 판. 그림은 틀림(배열 하나만 샘플).
            struct v2f { float4 vertex:SV_POSITION; float4 color:COLOR; float2 uv:TEXCOORD0; };
            v2f vert(appdata v)
            {
                uint a=(uint)(v.vertex.x+0.5)*60u;
                float3 p=asfloat(_CollapseVerts.Load3(a));
                float4 uvi=asfloat(_CollapseVerts.Load4(a+28));
                v2f o;o.vertex=UnityObjectToClipPos(float4(p,1));o.color=asfloat(_CollapseVerts.Load4(a+12));o.uv=uvi.xy;return o;
            }
            float4 frag(v2f v):SV_Target
            {
                float4 q=_SfDecoTex0.SampleLevel(sampler_linear_clamp,float3(frac(v.uv),0),0)*v.color;q.rgb*=q.a;return q;
            }
#endif
            ENDHLSL
        }
    }
}
'''
final_text = (shader.replace('TEXTURE_COUNT', str(arrays + direct)).replace('ARRAY_COUNT', str(arrays)).replace('PROPERTIES', properties).replace('DECLARATIONS', declarations).replace('BRANCHES', '\n'.join(branches)))
Path(__file__).with_name('GpuDecoBatch.shader').write_text(final_text, encoding='utf-8')
# 혼합 모드 판: 같은 이름의 GrabPass(_BLENDMODES_UnifiedGrabTexture)로 원래 Blend Modes 셰이더들과 화면 복사본을 공유한다.
blend_text = final_text.replace('Shader "StutterFix/GpuDecoBatch"', 'Shader "StutterFix/GpuDecoBatchBlend"')
blend_text = blend_text.replace('        Pass\n        {', '        GrabPass { }\n        Pass\n        {', 1)
blend_text = blend_text.replace('            HLSLPROGRAM\n', '            HLSLPROGRAM\n            #define SF_BLEND 1\n', 1)
blend_text = blend_text.replace('            ByteAddressBuffer _CollapseVerts;', '            ByteAddressBuffer _CollapseVerts;\n            Texture2D _GrabTexture;', 1)
# 게임 장식은 Hidden/BlendModes/SpritesDefault/Grab: 그리기마다 화면을 복사하는 이름 없는 GrabPass. 혼합 항목은 구간 하나에 하나씩만 둔다.
blend_text = blend_text.replace('_BLENDMODES_UnifiedGrabTexture.SampleLevel', '_GrabTexture.SampleLevel')
assert 'GrabPass { }' in blend_text and 'SF_BLEND 1' in blend_text and 'Texture2D _GrabTexture' in blend_text and '_GrabTexture.SampleLevel' in blend_text
Path(__file__).with_name('GpuDecoBatchBlend.shader').write_text(blend_text, encoding='utf-8')
