"""Generate explicit SM5 resource branches; no dynamic resource indexing or extra samplers."""
from pathlib import Path
import re

policy = (Path(__file__).resolve().parents[2] / 'DrawCollapsePolicy.cs').read_text(encoding='utf-8-sig')
arrays = int(re.search(r'const int ArrayBindings=(\d+);', policy).group(1))
direct = int(re.search(r'const int DirectBindings=(\d+);', policy).group(1))
assert arrays + direct <= 64, 'Unity shader texture parameter limit exceeded'
# 배열 텍스처는 모든 구간이 같은 것을 쓰므로 전역(_SfDecoTex*)으로 한 번만 묶고 Properties 에 두지 않는다(재질 속성이 적을수록 그리기 호출마다 드는 CPU 가 준다).
properties = ''
# 직접 텍스처는 Properties 에 두지 않는다: 재질이 값을 갖지 않으면 전역 텍스처(Shader.SetGlobalTexture)를 쓴다.
declarations = '\n'.join(f'            Texture2DArray _SfDecoTex{i};' for i in range(arrays))
few = int(re.search(r'const int FewDirectBindings=(\d+);', policy).group(1))
declarations += '\n#if defined(DIRECT_FEW)\n' + '\n'.join(f'            Texture2D _Big{i};' for i in range(few)) + f'\n            float _DirectMap[{direct}];'
declarations += '\n#elif !defined(NO_DIRECT_TEXTURES)\n' + '\n'.join(f'            Texture2D _Big{i};' for i in range(direct)) + '\n#endif'
def leaf(i):
    texture = f'_SfDecoTex{i}' if i < arrays else f'_Big{i-arrays}'
    coord = 'float3(uv,v.info.y)' if i < arrays else 'v.uv'
    return (f'if(usePoint) c={texture}.SampleLevel(sampler_point_clamp,{coord},0); '
            f'else c={texture}.SampleLevel(sampler_linear_clamp,{coord},0);')
def tree(lo, hi, indent):
    if lo == hi:
        return f'{indent}{{ {leaf(lo)} }}'
    mid = (lo + hi) // 2
    left = tree(lo, mid, indent + '    ')
    right = tree(mid + 1, hi, indent + '    ')
    nl = chr(10)
    return f'{indent}[branch] if(binding<={mid}) {{' + nl + left + nl + f'{indent}}} else {{' + nl + right + nl + f'{indent}}}'
branches = ['#ifdef NO_DIRECT_TEXTURES', tree(0, arrays - 1, '                '),
            '#elif defined(DIRECT_FEW)',
            f'                // 구간이 쓰는 직접 텍스처만 {few}칸에 다시 매긴다(재질의 _DirectMap). 그림은 같고 바인딩 수·셰이더 크기만 준다.',
            f'                if(binding>={arrays}) binding={arrays}+(int)_DirectMap[binding-{arrays}];',
            tree(0, arrays + few - 1, '                '),
            '#else', tree(0, arrays + direct - 1, '                '), '#endif']
shader = '''// Generated by generate-drawcollapse-shader.py. Unity D3D11: TEXTURE_COUNT textures (ARRAY_COUNT with NO_DIRECT_TEXTURES), two samplers.
Shader "StutterFix/GpuDecoBatch"
{
    Properties
    {
PROPERTIES
        _SrcBlend ("Source blend", Float) = 1
        _DstBlend ("Destination blend", Float) = 10
        _BlendOp ("Blend operation", Float) = 0
    }
    SubShader
    {
        Tags { "Queue"="Transparent" "IgnoreProjector"="True" "RenderType"="Transparent" "DisableBatching"="True" }
        Cull Off
        Lighting Off
        ZWrite Off
        ZTest LEqual
        Blend [_SrcBlend] [_DstBlend]
        BlendOp [_BlendOp]
        Pass
        {
            HLSLPROGRAM
            #pragma target 5.0
            #pragma only_renderers d3d11
            #pragma vertex vert
            #pragma fragment frag
            #pragma multi_compile_local _ NO_DIRECT_TEXTURES DIRECT_FEW
            #include "UnityCG.cginc"
DECLARATIONS
            SamplerState sampler_point_clamp;
            SamplerState sampler_linear_clamp;
            ByteAddressBuffer _CollapseVerts;
            float _LodMode;
            float4 _LodTarget;
            Texture2D _LodTex;
            struct appdata { float3 vertex:POSITION; };
            struct v2f { float4 vertex:SV_POSITION; float4 color:COLOR; float2 uv:TEXCOORD0; nointerpolation float2 info:TEXCOORD1; nointerpolation float4 region:TEXCOORD2; };
            v2f vert(appdata v)
            {
                // 정점 번호(x)로 전역 버퍼에서 위치·색·UV·텍스처 정보를 읽는다(60바이트: 위치 12, 색 16, uv+info 16, region 16).
                uint a=(uint)(v.vertex.x+0.5)*60u;
                float3 p=asfloat(_CollapseVerts.Load3(a));
                float4 uvi=asfloat(_CollapseVerts.Load4(a+28));
                v2f o;
                // 합치기 모드(렌더러 MPB): 정점 x 는 모서리 번호 0~3, 화면 전체 사각형을 그린다(저해상도 그림을 원래 순서 자리에 섞는다).
                if(_LodMode>0.5)
                {
                    uint cid=(uint)(v.vertex.x+0.5);
                    o.vertex=float4((cid==1||cid==2)?1:-1,cid>=2?1:-1,UNITY_NEAR_CLIP_VALUE,1);
                    o.color=1;o.uv=0;o.info=0;o.region=0;return o;
                }
                o.vertex=UnityObjectToClipPos(float4(p,1));o.color=asfloat(_CollapseVerts.Load4(a+12));o.uv=uvi.xy;o.info=uvi.zw;o.region=asfloat(_CollapseVerts.Load4(a+44));return o;
            }
            float4 frag(v2f v):SV_Target
            {
                if(_LodMode>0.5)return _LodTex.SampleLevel(sampler_linear_clamp,v.vertex.xy*_LodTarget.zw,0);
                bool usePoint=v.info.x>=128;int binding=(int)v.info.x%128;
                // 모든 텍스처가 밉 1단이라 SampleLevel(0) 은 SampleGrad 와 같다(미분·그래디언트 필요 없음).
                // Clamp to the copied rectangle's texel centres so padded BC blocks never bleed.
                float2 uv=clamp(v.uv*v.region.xy,v.region.zw,v.region.xy-v.region.zw);
                float4 c=0;
BRANCHES
                c*=v.color;c.rgb*=c.a;return c;
            }
            ENDHLSL
        }
    }
}
'''
Path(__file__).with_name('GpuDecoBatch.shader').write_text(shader.replace('TEXTURE_COUNT', str(arrays + direct)).replace('ARRAY_COUNT', str(arrays)).replace('PROPERTIES', properties).replace('DECLARATIONS', declarations).replace('BRANCHES', '\n'.join(branches)), encoding='utf-8')
